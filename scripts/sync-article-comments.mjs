import {readFileSync,writeFileSync,readdirSync,existsSync,mkdirSync} from 'node:fs';
import {join} from 'node:path';
const paths=[];
function scan(dir){
 if(!existsSync(dir))return;
 for(const e of readdirSync(dir,{withFileTypes:true})){
  const file=join(dir,e.name);if(e.isDirectory()){scan(file);continue;}if(!file.endsWith('.html'))continue;
  let html=readFileSync(file,'utf8');
  if(/name="robots"[^>]*noindex/.test(html)||!/<article\b/i.test(html))continue;
  const path=html.match(/rel="canonical" href="https:\/\/talkglobalapp.com([^"]+)"/)?.[1];
  if(!path||/^\/(artigos|blog|noticias)\/$/.test(path))continue;
  paths.push(path);
  if(!html.includes('data-article-comments')){
   const section=`\n<section class="article-comments" data-article-comments aria-labelledby="comments-title">\n<h2 id="comments-title">Vamos conversar?</h2>\n<p>O que você achou? Conte sua experiência ou deixe uma pergunta.</p>\n<p>Os comentários passam por aprovação antes de aparecer. Converse com respeito e não compartilhe dados pessoais.</p>\n<div data-comments-app><p>Carregando comentários…</p></div>\n<noscript>Ative o JavaScript para ler e enviar comentários.</noscript>\n</section>\n`;
   html=html.replace(/<\/article>/i,section+'</article>');
   html=html.replace('</head>','<link rel="stylesheet" href="/assets/article-comments.css">\n</head>');
   html=html.replace('</body>','<script src="/assets/article-comments.js" defer></script>\n</body>');
   writeFileSync(file,html);
  }
 }
}
['artigos','blog','noticias'].forEach(scan);
mkdirSync('lib',{recursive:true});writeFileSync('lib/article-paths.js',`// Generated by scripts/sync-article-comments.mjs\nexport default ${JSON.stringify([...new Set(paths)].sort(),null,2)};\n`);
console.log(`Comentários em ${paths.length} artigos.`);
